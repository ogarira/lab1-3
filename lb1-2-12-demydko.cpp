#include <iostream>  // Підключення бібліотеки введення-виведення (для cout та cin)
#include <cmath>     // Підключення математичної бібліотеки (для pow та cos)
using namespace std; // Використання стандартного простору імен (щоб не писати std::)
int main() // Головна функція, з якої починається виконання програми
{  // Початок тіла функції
double x, y, z;  // Оголошення трьох дробових змінних для вхідних даних x, y, z
cout << "Enter values for x, y, z: "; // Виведення на екран запиту для користувача
cin >> x >> y >> z; // Зчитування введених чисел з клавіатури у змінні
double g = (x < (y - x)) ? x : (y - x); // Обчислення чисельника: шукаємо min(x, y-x) за допомогою тернарного оператора
double k = (y * z) > pow(x, 2) ? (y * z) : pow(x, 2); // Обчислення частини знаменника: шукаємо max(y*z, x^2) за допомогою тернарного оператора
if (abs(k + cos(2 * pow(z, 3))) < 1e-9) // Перевірка знаменника на нуль з урахуванням похибки (abs — модуль, 1e-9 — це 10^-9
{  // Початок блока, якщо знаменник дорівнює нулю
		cout << "\nError: division by zero!" << endl; // Виведення повідомлення про помилку ділення
} // Кінець блока умови if
	else // Гілка "інакше", якщо знаменник не нульовий
{ // Початок блока для успішного розрахунку
double F = g / (k + cos(2 * pow(z, 3))); // Обчислення фінального значення F
cout << "F = " << F << endl; // Виведення порахованого результату F на екран
}// Кінець блока else
system("pause"); // Зупинка консолі, щоб вікно не закрилося відразу і було видно результат
return 0; // Повернення знаку успішного завершення програми (код 0)
} // Кінець усього файлу та закриття функції main